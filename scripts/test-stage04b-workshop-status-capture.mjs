import assert from 'node:assert/strict'
import fs from 'node:fs'
import { DatabaseSync } from 'node:sqlite'

const migration = fs.readFileSync('migrations/0084_v72_workshop_settlement_status_capture.sql','utf8')
const baseline = fs.readFileSync('migrations/0083_v72_workshop_settlement_foundation.sql','utf8')
const wrangler = fs.readFileSync('wrangler.jsonc','utf8')
assert.match(wrangler, /"name"\s*:\s*"orders-app-branch2"/)
assert.match(wrangler, /"database_name"\s*:\s*"orders_db_branch2"/)
assert.match(wrangler, /"database_id"\s*:\s*"40065052-854e-44b8-bcd5-251bdd488301"/)
assert.doesNotMatch(wrangler,/orders_db_prod|17e68a41-1d58-4a36-8a63-47c3e32443c4/)
assert.match(migration,/AFTER UPDATE OF status ON workshop_tasks/)
assert.doesNotMatch(migration,/(?:ALTER|DROP)\s+TABLE\s+(?:orders|workshop_tasks|order_items)\b/i)
const db=new DatabaseSync(':memory:')
db.exec('PRAGMA foreign_keys=ON')
db.exec("CREATE TABLE workshop_tasks (id INTEGER PRIMARY KEY, order_id INTEGER NOT NULL, external_order_id TEXT NOT NULL, product_name_snapshot TEXT NOT NULL, quantity INTEGER NOT NULL DEFAULT 1, gender_snapshot TEXT, color_snapshot TEXT, material_snapshot TEXT, length_snapshot TEXT, size_snapshot TEXT, status TEXT NOT NULL)")
db.exec(baseline)
db.exec(migration)
db.exec(migration)
const add=db.prepare('INSERT INTO workshop_tasks(id,order_id,external_order_id,product_name_snapshot,quantity,status) VALUES(?,?,?,?,?,?)')
add.run(1,11,'A-1','Шапан',2,'active')
add.run(2,12,'A-2','Жилет',3,'active')
add.run(3,13,'A-3','Кепка',1,'done')
const change=db.prepare('UPDATE workshop_tasks SET status=? WHERE id=?')
const events=()=>db.prepare('SELECT id,event_type,event_key,workshop_task_id,product_name_snapshot,quantity,amount_delta,related_event_id FROM workshop_settlement_events ORDER BY id').all()
assert.equal(db.prepare('SELECT enabled FROM workshop_settlement_capture_control WHERE id=1').get().enabled,0)
change.run('done',1)
change.run('active',1)
change.run('active',3)
assert.equal(events().length,0,'old status changes must remain inert')
db.exec("UPDATE workshop_settlement_capture_control SET enabled=1,activated_at='2026-10-09T00:00:00Z' WHERE id=1")
db.exec(migration)
assert.equal(db.prepare('SELECT enabled FROM workshop_settlement_capture_control WHERE id=1').get().enabled,1)
change.run('done',1)
const first=events()[0]
assert.equal(first.event_type,'completion')
assert.equal(first.quantity,2)
assert.equal(first.amount_delta,null,'unconfirmed prices must not become zero')
change.run('done',1)
change.run('ready',1)
assert.equal(events().length,1,'replay and done-to-ready must not duplicate')
db.exec("UPDATE workshop_tasks SET status='done' WHERE id IN (2,3)")
assert.equal(events().filter(e=>e.event_type==='completion').length,3,'bulk path must be covered')
change.run('active',1)
assert.equal(events().at(-1).related_event_id,first.id)
assert.equal(events().at(-1).event_type,'completion_reversal')
change.run('active',1)
assert.equal(events().filter(e=>e.event_type==='completion_reversal').length,1)
change.run('done',1)
const latest=events().at(-1)
assert.notEqual(latest.event_key,first.event_key)
assert.equal(events().filter(e=>e.event_type==='completion'&&e.workshop_task_id===1).length,2)
db.exec('UPDATE workshop_settlement_capture_control SET enabled=0 WHERE id=1')
change.run('active',1)
assert.equal(events().at(-1).related_event_id,latest.id)
const n=events().length
change.run('done',1)
assert.equal(events().length,n,'capture disabled again')
db.close()
console.log('STAGE04-B STATUS CAPTURE PASSED — disabled by default, single/bulk/retry/cycles, compensating reversals and pending prices')
