import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = file => fs.readFileSync(path.join(root, file), 'utf8')
const check = (condition, message) => { if (!condition) throw new Error(message) }
const section = (text, start, end = '') => {
  const i = text.indexOf(start)
  check(i >= 0, `missing section ${start}`)
  if (!end) return text.slice(i)
  const j = text.indexOf(end, i + start.length)
  check(j > i, `missing section end ${end}`)
  return text.slice(i, j)
}

try {
  const app = read('src/App.tsx')
  const view = read('src/features/sections/OrderEditorSection.tsx')
  const worker = read('worker/domains/orders-write.ts')
  const types = read('worker/core/types.ts')
  const persist = section(app, 'async function persistOrder(', 'async function saveSelectedOrder()')
  const updatePayment = section(app, 'function updateEditorPayment(', 'function addEditorPayment(')
  const edit = section(worker, 'export async function updateOrderCritical(', 'export async function getOrder(')

  check(!updatePayment.includes("if (payment.id && field !== 'method') return payment"), 'persisted ordinary payment is still method-only')
  check(updatePayment.includes("payment.id && payment.paymentKind === 'extra' && field !== 'method'"), 'exchange-extra editor guard missing')
  check(updatePayment.includes("!payment.id && field === 'paymentDate' && payment.paymentKind === 'primary'"), 'creation-time primary date guard missing')
  check(updatePayment.includes("!payment.id && nextKind === 'primary'"), 'posted primary correction still risks forcing date to order date')
  check(view.includes("Boolean(payment.id && payment.paymentKind === 'extra')"), 'exchange-linked fields are not protected in UI')
  check(view.includes('Дату, сумму, способ, смысл и комментарий можно исправить'), 'posted ordinary correction explanation missing')
  check(view.includes('сумму, дату и смысл меняйте через операцию обмена'), 'exchange-extra ownership explanation missing')
  check(persist.includes('const paymentCorrections:'), 'frontend correction snapshot builder missing')
  check(persist.includes('expectedPaymentDate: oldPaymentDate'), 'frontend CAS date snapshot missing')
  check(persist.includes('expectedAmount: oldAmount'), 'frontend CAS amount snapshot missing')
  check(persist.includes('expectedPaymentKind: oldPaymentKind'), 'frontend CAS kind snapshot missing')
  check(persist.includes('expectedComment: oldComment'), 'frontend CAS comment snapshot missing')
  check(persist.includes('paymentCorrections,'), 'order PATCH does not send payment corrections')
  check(!persist.includes('payments: nextDraft.payments'), 'normal order edit unexpectedly rewrites full payment history')
  check(types.includes('paymentCorrections?: Array<{'), 'typed payment correction request contract missing')
  check(types.includes('paymentMethodCorrections?: Array<{ paymentId?: number; method?: string }>'), 'cached-client method-only compatibility missing')
  check(edit.includes('rawPaymentCorrections'), 'backend generalized correction input missing')
  check(edit.includes('requested.expectedPaymentDate'), 'server CAS check missing')
  check(edit.includes('после открытия редактора'), 'stale payment conflict is not user-visible')
  check(edit.includes('isExchangeExtra && nonMethodChanged'), 'exchange-extra non-method correction guard missing')
  check(edit.includes("newPaymentKind === 'extra'"), 'ordinary payment can become exchange-extra')
  check(edit.includes('paymentCorrectionAmountDelta'), 'order received/debt totals do not incorporate corrected amount')
  check(edit.includes('UPDATE payments SET payment_date = ?, method = ?, amount = ?, payment_kind = ?, comment = ? WHERE id = ? AND order_id = ?'), 'same payment row/id is not corrected in place')
  check(edit.includes("eventType: 'payment_reversal'"), 'old monetary fact reversal missing')
  check(edit.includes('eventDate: correction.oldPaymentDate'), 'reversal does not stay on old business date')
  check(edit.includes('eventDate: correction.newPaymentDate'), 'corrected money fact does not move to corrected date')
  check(edit.includes('eventType: correction.newRelatedType'), 'corrected operation kind not reflected in finance history')
  check(edit.includes("reason: 'payment_correction'"), 'generic audited correction reason missing')
  check(edit.includes('payment-correction:${correction.paymentId}:old'), 'old event is not request-idempotent')
  check(edit.includes('payment-correction:${correction.paymentId}:new'), 'new event is not request-idempotent')
  check(edit.includes('newTrackedCashAmount - oldTrackedCashAmount'), 'cash correction is not delta-based')
  check(edit.includes('payment-correction:${criticalOperation.requestId}:${correction.paymentId}:cash-delta'), 'cash delta is not request-idempotent')
  check(edit.includes("c.source_type IN ('payment_method_correction', 'payment_correction')"), 'cash lineage does not survive successive corrections')
  check(edit.indexOf("criticalOperation.row.step === 'shipping_committed' && paymentCorrectionCount") > edit.indexOf("advanceCriticalOperation(db, criticalOperation, 'shipping_committed'"), 'payment correction runs before core order edit is committed')
  check(edit.includes('const rewritePayments = !deletingOrder'), 'legacy full-payment rewrite detection unexpectedly removed')
  check(edit.includes('} else if (p.rewritePayments) {'), 'legacy full-payment rewrite path unexpectedly removed')
  console.log('ORDER EDIT SAFE PAYMENT CORRECTION PASSED — posted ordinary payments correct date/amount/method/kind/comment in place with CAS, finance reversal+replacement, delta cash and exchange ownership')
} catch (error) {
  console.error(`ORDER EDIT SAFE PAYMENT CORRECTION FAILED: ${error?.message || error}`)
  process.exit(1)
}
